    assert.equal(await page.locator('#cashEveningBank1000V749').inputValue(),'20');
    assert.equal(await page.locator('#cashEveningBank1000V749').evaluate(el=>el.readOnly),true);
    const notes=await page.locator('#cashResultBox > .cashBanknoteDetails').textContent();
