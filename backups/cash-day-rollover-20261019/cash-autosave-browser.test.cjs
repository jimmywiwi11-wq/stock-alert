    const record=Object.values(restored).find(x=>x.branch===1);
    assert.equal(Number(String(record.morningChange).replace(/,/g,'')),1500);
    assert.equal(record.exchangeTransactions[0].amount,4000);
    assert.equal(record.exchangeTransactions[0].note,'autosave offline test');
    assert.equal(await page.locator('#cashMorningSaveButton').textContent(),'เพิ่มเงินสดเปิดร้าน','autosaved typing is not an explicit morning confirmation');
    await page.locator('#cashClosingDetailButton').click();
    await page.locator('#cashClosingAmount1000').fill('20000');
    assert.equal(await page.locator('#cashClosingCount1000').inputValue(),'20');
    await page.locator('#cashClosingCount20').fill('20');
    assert.equal(await page.locator('#cashClosingAmount20').inputValue(),'400');
    await page.locator('#cashClosingAmount20').fill('400');
    await page.locator('#cashClosingAmount1').fill('13');
    await page.locator('#cashClosingAmount10').fill('20');
    await page.locator('#cashClosingAmount500').fill('');
