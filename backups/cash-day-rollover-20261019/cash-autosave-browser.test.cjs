    await page.waitForFunction(()=>typeof window.openCashBranch==='function');await page.evaluate(()=>window.openCashBranch(1));
    assert.equal(Number(await page.locator('#cashEveningTotalV749').inputValue()),20433,'detail survives reopening');
    assert.equal(await page.locator('#cashEveningBank1000V749').inputValue(),'20');
    await page.locator('#cashClosingDetailButton').click();
    await page.locator('#cashClosingAmount1000').fill('20500');
